// Sections fade up as they come into view; without IntersectionObserver, or with reduced motion, they simply show.
const dirObserver = 'IntersectionObserver' in window && !matchMedia('(prefers-reduced-motion: reduce)').matches
  ? new IntersectionObserver(es => es.forEach(e => { if (e.isIntersecting) { e.target.classList.add('rv-in'); dirObserver.unobserve(e.target); } }), { rootMargin: '0px 0px -8% 0px' })
  : null;
if (dirObserver) {
  document.documentElement.classList.add('rv-on');
  new MutationObserver(() => document.querySelectorAll('#main .rv:not(.rv-in)').forEach(el => dirObserver.observe(el)))
    .observe(document.getElementById('main'), { childList: true });
}

